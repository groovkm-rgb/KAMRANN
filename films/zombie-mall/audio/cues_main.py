# Main-film cues (exec'd inside mix.py). Times are SOURCE seconds, mapped with V().
def V(s): return s + TM['vo_offset'] + (TM['gap'] if s > TM['gap_at'] else 0)
def beep(f=1000, d=.18): tt = t_(d); return norm(np.sin(2 * np.pi * f * tt) * env(len(tt), .005, .03), .6)
def buzz(d=2.0): tt = t_(d); return norm(np.sign(np.sin(2 * np.pi * 160 * tt)) * (np.sin(2 * np.pi * 2.2 * tt) > 0) * .5 * lpf(np.ones(len(tt)), 99999) , .5)
def rattle(d=2.0): tt = t_(d); x = bpf(noise(d), 200, 3000) * (0.5 + .5 * np.sign(np.sin(2 * np.pi * 22 * tt))); return norm(x * env(len(x), .05, .2), .8)
def powerdown(): d = 2.2; tt = t_(d); f = 120 * np.exp(-tt * 1.4) + 20; ph = 2 * np.pi * np.cumsum(f) / SR; return norm((np.sin(ph) + .3 * np.sign(np.sin(ph))) * np.exp(-tt * .9), .9)
def engine(d=3.0): tt = t_(d); f = 28 + 10 * np.clip(tt / .8, 0, 1); ph = 2 * np.pi * np.cumsum(f) / SR; x = np.sign(np.sin(ph)) * .6 + lpf(noise(d), 400) * 3; return norm(lpf(x, 900) * env(len(tt), .3, .5), .9)
def alarm(d=4.0): tt = t_(d); f = 700 + 500 * (np.sin(2 * np.pi * 2.5 * tt) > 0); ph = 2 * np.pi * np.cumsum(f) / SR; return norm(np.sign(np.sin(ph)) * .6, .7) * env(len(tt), .01, .3)
def slam(): d = .9; tt = t_(d); return norm(np.sin(2 * np.pi * 55 * tt) * np.exp(-tt * 9) + lpf(noise(d), 2500) * np.exp(-tt * 20), 1)
def rotor(d=10.0, rise=1): tt = t_(d); a = np.clip(tt / (d * .8), 0, 1) if rise else np.clip(1 - tt / d, 0, 1); pulse = (np.sin(2 * np.pi * 11 * tt) > .6) * 1.0; x = lpf(noise(d), 500) * 4 * pulse + .3 * lpf(noise(d), 200) * 3; return norm(x * a, .9)
def static(d=4.0): return norm(bpf(noise(d), 1000, 7000) * (0.7 + .3 * rng.random(int(d * SR))), .45) * env(int(d * SR), .05, .1)
def crowd(d=3.0): tt = t_(d); return norm(bpf(noise(d), 500, 2500) * (0.6 + .4 * np.sin(2 * np.pi * 3 * tt)), .7) * env(int(d * SR), .2, .5)
def bang(): return norm(slam() * .8 + lpf(noise(.9), 600)[:int(.9 * SR)] * np.exp(-t_(.9) * 12), 1)
def rain(d): return norm(bpf(noise(d), 1500, 9000), .5) * env(int(d * SR), .5, .5)
